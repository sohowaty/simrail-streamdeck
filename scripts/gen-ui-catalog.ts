/**
 * Writes the command catalog for the property inspector to ui/catalog.js (run by `npm run build`).
 * Shipping it as a static script means the lists always fill, even before the plugin answers
 * (Stream Deck only routes plugin → panel messages after it has told the plugin the panel opened).
 */
import { writeFileSync } from "node:fs";

import { catalogPayload } from "../src/catalog";

const { status: _s, topics: _t, event: _e, ...catalog } = catalogPayload({}, undefined);
const out = "com.simrailmqtt.streamdeck.sdPlugin/ui/catalog.js";
writeFileSync(out, `// Generated by scripts/gen-ui-catalog.ts – do not edit.\nwindow.SIMRAIL_CATALOG = ${JSON.stringify(catalog)};\n`);
console.log(`wrote ${out}`);
